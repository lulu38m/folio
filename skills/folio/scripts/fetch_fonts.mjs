#!/usr/bin/env node
// Download open-licence fonts from the Fontsource packages on npm and write self-hosted @font-face rules.
// Usage: node fetch_fonts.mjs --out site/public/fonts "Schibsted Grotesk:400,800" "Newsreader:400,400i"
// Needs npm on the PATH and access to registry.npmjs.org. Writes <out>/*.woff2 and <out>/fonts.css.
// Subset: latin (covers French: é è à ç œ « » € and the narrow no-break space). Add --ext for latin-ext.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, copyFileSync, existsSync, writeFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";

const args = process.argv.slice(2);
let out = "site/public/fonts";
let ext = false;
const specs = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--out") out = args[++i];
  else if (args[i] === "--ext") ext = true;
  else specs.push(args[i]);
}
if (!specs.length) {
  console.error('usage: fetch_fonts.mjs --out site/public/fonts "Family:400,700" ["Other:400,400i"]');
  process.exit(1);
}
out = resolve(out);
mkdirSync(out, { recursive: true });
const tmp = mkdtempSync(join(tmpdir(), "folio-fonts-"));
let css = "/* Self-hosted fonts (Fontsource, SIL Open Font License). Generated by folio/fetch_fonts.mjs */\n";
let failed = 0;

for (const spec of specs) {
  const [family, weightList = "400"] = spec.split(":");
  const slug = family.trim().toLowerCase().replace(/\s+/g, "-");
  const pkg = `@fontsource/${slug}`;
  let dir;
  try {
    const tgz = execFileSync("npm", ["pack", pkg, "--silent", "--pack-destination", tmp], { encoding: "utf8" }).trim().split("\n").pop();
    dir = join(tmp, slug);
    mkdirSync(dir, { recursive: true });
    execFileSync("tar", ["xzf", join(tmp, tgz), "-C", dir]);
  } catch (e) {
    console.error(`FAIL ${family}: could not fetch ${pkg} (${e.message.split("\n")[0]})`);
    failed++;
    continue;
  }
  const files = readdirSync(join(dir, "package", "files"));
  for (const w of weightList.split(",").map((s) => s.trim()).filter(Boolean)) {
    const italic = w.endsWith("i");
    const weight = italic ? w.slice(0, -1) : w;
    const style = italic ? "italic" : "normal";
    for (const subset of ext ? ["latin", "latin-ext"] : ["latin"]) {
      const name = `${slug}-${subset}-${weight}-${style}.woff2`;
      if (!files.includes(name)) {
        console.error(`FAIL ${family} ${weight} ${style}: not in ${pkg} (available weights: ${[...new Set(files.filter((f) => f.includes("-latin-") && f.endsWith("-normal.woff2")).map((f) => f.split("-latin-")[1].split("-")[0]))].join(", ")})`);
        failed++;
        continue;
      }
      copyFileSync(join(dir, "package", "files", name), join(out, name));
      css += `@font-face{font-family:"${family.trim()}";font-style:${style};font-weight:${weight};font-display:swap;src:url("${name}") format("woff2");}\n`;
      console.log(`ok   ${family} ${weight} ${style} -> ${name}`);
    }
  }
}
writeFileSync(join(out, "fonts.css"), css);
console.log(`wrote ${join(out, "fonts.css")}. layouts/Base.astro links /fonts/fonts.css; preload the first screen's files as /fonts/<file>.woff2.`);
if (failed) process.exit(2);
